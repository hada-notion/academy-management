-- 함수(_shared/appCopy.ts SKIP_PROPS)가 앞으로 복사하지 않는 칸을, 이미 들어간 줄에서도 지운다(학부모 리포트 토큰, 웹훅 칸, 노션 계정).
-- 다시 적용해도 같은 결과다. Notion은 건드리지 않는다.
update public.app_rows
   set props = props - '토큰' - '웹훅 링크' - '웹훅 정보' - '웹훅ID' - '웹훅 버튼' - '노션 계정' - '노션 아이디'
 where props ?| array['토큰', '웹훅 링크', '웹훅 정보', '웹훅ID', '웹훅 버튼', '노션 계정', '노션 아이디'];
